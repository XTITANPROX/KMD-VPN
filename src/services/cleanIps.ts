export function parseIpsField(ips: unknown): string[] {
  if (!ips) return [];
  try {
    if (Array.isArray(ips) && ips.length) return ips.filter((x): x is string => typeof x === "string");
    if (typeof ips === "string") {
      const arr = JSON.parse(ips);
      if (Array.isArray(arr) && arr.length) return arr;
    }
  } catch {}
  return [];
}
